const ZWNJ = '\u200C';
const PLACEHOLDER = '\uFFFC';

function isCorrect(word) {
    if (word.length <= 1) return true;
    if (WHITELIST.has(word)) return true;
    if (DICT.has(word)) return false;
    // بررسی با نیم‌فاصله‌های مختلف
    const withoutZwnj = word.replace(new RegExp(ZWNJ, 'g'), '');
    if (WHITELIST.has(withoutZwnj)) return true;
    const withSpace = word.replace(new RegExp(ZWNJ, 'g'), ' ');
    if (WHITELIST.has(withSpace)) return true;
    return false;
}

function spellCheck(text) {
    const corrections = [];
    let result = text;

    // گام ۰: حفظ نیم‌فاصله‌های موجود
    result = result.replace(new RegExp(ZWNJ, 'g'), PLACEHOLDER);

    // گام ۱: عبارات چندکلمه‌ای (اولویت با بلندترین)
    const multiWord = [...DICT.entries()]
        .filter(([k]) => k.includes(' ') || k.includes(PLACEHOLDER))
        .sort((a, b) => b[0].length - a[0].length);

    for (const [wrong, correct] of multiWord) {
        const escaped = wrong.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        const regex = new RegExp(escaped, 'g');
        if (regex.test(result)) {
            corrections.push({ type: 'phrase', original: wrong, corrected: correct });
            result = result.replace(regex, correct);
        }
    }

    // گام ۲: کلمات تکی
    const singleWord = [...DICT.entries()]
        .filter(([k]) => !k.includes(' ') && !k.includes(PLACEHOLDER))
        .sort((a, b) => b[0].length - a[0].length);

    for (const [wrong, correct] of singleWord) {
        const escaped = wrong.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        const regex = new RegExp(`(?<![\\u0600-\\u06FF\\u200C])${escaped}(?![\\u0600-\\u06FF\\u200C])`, 'g');
        if (regex.test(result)) {
            corrections.push({ type: 'exact', original: wrong, corrected: correct });
            result = result.replace(regex, correct);
        }
    }

    // گام ۳: اصلاح نیم‌فاصله برای «می» و «نمی» (فقط فاصلهٔ کامل)
    result = result.replace(/\bمی\s+(?=[آابپتثجچحخدذرزژسشصضطظعغفقکگلمنوهی])/g, 'می‌');
    result = result.replace(/\bنمی\s+(?=[آابپتثجچحخدذرزژسشصضطظعغفقکگلمنوهی])/g, 'نمی‌');

    // گام ۴: اصلاح فاصلهٔ علائم نگارشی
    result = result.replace(/ +([.،؛:?!»\)\]\}])/g, '$1');
    result = result.replace(/([«\(\[\{]) +/g, '$1');
    result = result.replace(/([.،؛:?!])([^\s\d\n«\(\[\{])/g, '$1 $2');

    // گام ۵: نیم‌فاصله برای «ها»ی جمع (فقط فاصلهٔ کامل)
    result = result.replace(/([آابپتثجچحخدذرزژسشصضطظعغفقکگلمنوهی])\s+ها(?=\s|$|[.،؛:?!»\)\]\}])/g, '$1‌ها');

    // گام ۶: یکسان‌سازی اعداد عربی ← فارسی
    const arabicToPersian = { '٠':'۰','١':'۱','٢':'۲','٣':'۳','٤':'۴','٥':'۵','٦':'۶','٧':'۷','٨':'۸','٩':'۹' };
    for (const [ar, fa] of Object.entries(arabicToPersian)) {
        result = result.replace(new RegExp(ar, 'g'), fa);
    }

    // گام ۷: بازیابی نیم‌فاصله‌های اصلی
    result = result.replace(new RegExp(PLACEHOLDER, 'g'), ZWNJ);

    // حذف موارد تکراری
    const unique = [];
    const seen = new Set();
    for (const c of corrections) {
        const key = c.original + '→' + c.corrected;
        if (!seen.has(key)) { seen.add(key); unique.push(c); }
    }

    return {
        original: text,
        corrected: result.trim(),
        corrections: unique,
        has_errors: unique.length > 0,
        error_count: unique.length
    };
}

